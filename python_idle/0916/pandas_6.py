# -------------------------------------------------------------------------
# 1. 匯入 3 模組
# -------------------------------------------------------------------------
# 匯入 pandas 模組，並設定別名為 pd（這是 Python 資料分析界的標準慣例縮寫）
import pandas as pd

# -------------------------------------------------------------------------
# 2. 準備原始資料（這是一個「包含多個字典的清單」）
# -------------------------------------------------------------------------
# 每個字典代表「一筆商品資料（一列 Row）」，字典的 Key 將自動成為表格的欄位名稱（Columns）
products = [
    {"name": "咖啡機", "price": 5000, "rating": 4.8},
    {"name": "磨豆機", "price": 1200, "rating": 4.2},
    {"name": "濾紙", "price": 150, "rating": 4.9},
    {"name": "保溫杯", "price": 800, "rating": 3.5}
]

# -------------------------------------------------------------------------
# 3. 建立並印出 DataFrame
# -------------------------------------------------------------------------
# 將字典清單傳入 pd.DataFrame()，轉換成類似 Excel 的二維表格物件
df = pd.DataFrame(products)

# 印出完整的表格內容
# 輸出時左側會自動生成從 0 開始的索引（Index）
print(df)
print('=' * 20)

# -------------------------------------------------------------------------
# 4. 資料篩選與過濾（核心重點）
# -------------------------------------------------------------------------
# 這行程式碼在底層其實分為兩個步驟執行：
# 
# 步驟 (A)：df["rating"] > 4.5
# 系統會逐行檢查 rating 欄位是否大於 4.5，並回傳一個由布林值組成的數列（Series）：
# 0     True  (4.8 > 4.5)
# 1    False  (4.2 不大於 4.5)
# 2     True  (4.9 > 4.5)
# 3    False  (3.5 不大於 4.5)
#
# 步驟 (B)：df[...] 
# 把剛剛產生的 [True, False, True, False] 布林遮罩（Boolean Mask）丟回 df 中。
# 只有 True 的那一列資料（第 0 列的咖啡機、第 2 列的濾紙）才會被保留並印出來。
print(df[(df["rating"] > 4.5) & (df['price'] > 2000)])
