import pandas as pd

# 1. 建立包含髒資料的原始 DataFrame
data = {"product": [" iPhone ", "iPad"], "price": ["$30,000", "$20,000"]}
df = pd.DataFrame(data)

# -------------------------------------------------------------------------
# 清洗動作 (1)：去除 product 欄位多餘的空格
# -------------------------------------------------------------------------
# 使用 .str.strip() 可以同時移除字串前後的空白字元（例如 " iPhone " 變成 "iPhone"）
df["product"] = df["product"].str.strip()

# -------------------------------------------------------------------------
# 清洗動作 (2)：去除 price 欄位的 $ 與 , 記號，並轉為數值型態
# -------------------------------------------------------------------------
# 步驟 A：先用 .str.replace() 把 "$" 和 "," 都替換成空字串 ""
# 步驟 B：再用 .astype(int) 將清除符號後的字串（如 "30000"）強制轉換為整數型態
df["price"] = df["price"].str.replace("$", "", regex=False)
df["price"] = df["price"].str.replace(",", "", regex=False)
df["price"] = df["price"].astype(int)

# -------------------------------------------------------------------------
# 3. 檢查清洗後的結果
# -------------------------------------------------------------------------
print("--- 清洗後的 DataFrame ---")
print(df)

print("\n--- 檢查資料型態 ---")
print(df.dtypes)
