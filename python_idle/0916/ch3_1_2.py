import pandas as pd

# 1. 建立兩份爬蟲抓回來的原始數據
df_a = pd.DataFrame({"news": ["頭條 1"], "views": [500]})
df_b = pd.DataFrame({"news": ["頭條 2"], "views": [300]})

# -------------------------------------------------------------------------
# 任務重點 (1)：將兩份資料合併為 df_all，並確保索引（Index）不重複
# -------------------------------------------------------------------------
# 使用 pd.concat() 將兩個 DataFrame 以列表形式傳入進行縱向串接。
# 加上 ignore_index=True 參數，系統會自動忽略原本各自的 0，重新編排為全新的 0, 1 索引。
df_all = pd.concat([df_a, df_b], ignore_index=True)

print("--- 合併後的完整資料 (df_all) ---")
print(df_all)
print('=' * 30)

# -------------------------------------------------------------------------
# 任務重點 (2)：計算並印出合併後的「總觀看數 (views)」
# -------------------------------------------------------------------------
# 選取 "views" 欄位，並呼叫 .sum() 函數將該欄位的所有數值加總
total_views = df_all["views"].sum()

print(f"合併後的總觀看數 (views) 為：{total_views}")
