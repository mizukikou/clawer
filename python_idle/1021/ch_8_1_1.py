# ==============================================================================
# 實作題 1：兄弟節點的精準跳躍尋找
# 觀念重點：利用 .find_next_sibling() 自動跳過網頁原始碼中的換行與空白字元
# ==============================================================================

# 引入 Python 的 BeautifulSoup 網頁解析套件
import bs4

# 1. 定義原始碼字串 (題目給予的 HTML 結構)
# 注意：在 <td id="phone_label">電話</td> 與下一個 <td> 之間存在著多個換行與空白
html_doc = """
<tr>
    <td class="label">姓名</td>
    <td class="value">王大明</td>
    <td class="label" id="phone_label">電話</td>
    
    <td class="value">0912-345-678</td>
</tr>
"""

# 2. 將 HTML 字串丟入 BeautifulSoup 解析器，並指定使用內建的 html.parser
# 這行執行完後，soup 會變成一棵結構化的 DOM 樹狀物件
soup = bs4.BeautifulSoup(html_doc, "html.parser")


# ==============================================================================
# 步驟一：精確定位起點標籤
# ==============================================================================
# 使用 soup.find() 尋找全網頁中第一個符合以下條件的標籤：
# 標籤名稱為 "td" 且 屬性包含 id="phone_label"
label_tag = soup.find("td", id="phone_label")


# ==============================================================================
# 步驟二：精準跳躍至兄弟節點 (核心解題關鍵)
# ==============================================================================
# ⚠️ 為什麼不用 label_tag.next_sibling？
# 因為 next_sibling 非常嚴格，它會抓到「電話</td>」後面緊接著的「換行與空白字元」，導致抓不出文字。
# 
#  正確做法：使用 .find_next_sibling("td")
# 這個方法會聰明地「跳過」所有無意義的換行與空格，直接往後尋找下一個真正的 <td> 標籤物件。
phone_tag = label_tag.find_next_sibling("td")


# ==============================================================================
# 步驟三：提取文字並格式化輸出
# ==============================================================================
# 為了確保程式不會因為網頁臨時改版而當機，加入一個溫和的 if 判斷式 (防呆機制)
if phone_tag is not None:
    # 使用 .text 屬性將 <td>0912-345-678</td> 內部的 HTML 標籤剝離，只留下純文字
    phone_number = phone_tag.text
    
    # 依照題目要求的「輸出範例」格式進行標準輸出
    print(f"電話的數值是：{phone_number}")
else:
    # 萬一網頁結構出錯，找不到下一個兄弟標籤時的警示
    print("錯誤：找不到記錄電話號碼的兄弟標籤！")
