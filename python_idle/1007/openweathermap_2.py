import requests  # 💡 匯入網路請求模組，用來向 OpenWeather 伺服器發送請求與下載資料
import sys       # 💡 匯入系統模組，用來在發生錯誤時乾淨地中斷程式執行

def get_wind_direction(deg):
    """將風向角度 (0-360) 轉換為台灣常見的 8 個中文方位"""
    # 確保角度落在 0 ~ 360 之間
    deg = deg % 360
    
    # 依據每 45 度一個區間進行劃分（將 360 度切成 8 個方位）
    if 337.5 <= deg or deg < 22.5:
        return "北"
    elif 22.5 <= deg < 67.5:
        return "東北"
    elif 67.5 <= deg < 112.5:
        return "東"  # 👈 您的 68 度就會精準落在這個區間！
    elif 112.5 <= deg < 157.5:
        return "東南"
    elif 157.5 <= deg < 202.5:
        return "南"
    elif 202.5 <= deg < 247.5:
        return "西南"
    elif 247.5 <= deg < 292.5:
        return "西"
    elif 292.5 <= deg < 337.5:
        return "西北"
    return "未知"


# =================================================================
# 步驟 1：讀取外部文字檔中的 API 金鑰 (API KEY)
# =================================================================
# 使用原始字串 (r"...") 包裝路徑，防止 Windows 的反斜線 \ 觸發轉義警告
api_key_path = r"G:\我的雲端硬碟\Crawler\課程資料\筆記\20261007\API_KEY.txt"

# 使用 with open 語法開啟檔案，執行完畢後會自動關閉檔案、釋放記憶體
with open(api_key_path, "r") as file:
    # file.read() 讀取全部文字，.strip() 自動剃除前後不小心按到的空白或換行符 ( \n )
    api_key = file.read().strip()

# =================================================================
# 步驟 2：與使用者互動，取得 Google 地圖的座標字串
# =================================================================
print("【說明】請打開 Google Map，在目的地點擊右鍵，複製最上方的「緯度, 經度」（例如：25.0339, 121.5644）")
# input() 會在終端機暫停並等待使用者輸入，貼上後透過 .strip() 清除頭尾雜質空白
google_coords = input("請貼上 Google 地圖座標: ").strip()

# =================================================================
# 步驟 3：【單獨防錯區塊】只檢查與拆解 Google 座標格式
# =================================================================
# 💡 將 try-except 的範圍縮到最小，只管「字串有沒有成功被逗號切成兩半」。
# 💡 這樣後面不論發生什麼網路錯誤或 API 錯誤，都絕對不會再「誤報」成格式錯誤！
try:
    # 核心拆解：Google 地圖複製的文字固定以英文逗號隔開 (如 "24.929, 121.254")
    # .split(",") 會以逗號為界線，把左邊分給第一個變數 lat，右邊分給第二個變數 lon
    lat, lon = google_coords.split(",")
    
    # 拆開後，分別使用 .strip() 拿掉個別字串前後殘留的空格（特別是經度前方通常自帶一格空格）
    lat = lat.strip()
    lon = lon.strip()
    
    # 印出解析成功的經緯度數值，確認拆分正確
    print(f"➔ 成功解析座標！緯度 (lat): {lat} | 經度 (lon): {lon}")

except ValueError:
    # 如果使用者貼上的文字沒有逗號、或是按到兩次貼上，導致 split 失敗，就會跳到這裡
    print("❌ 輸入格式錯誤！請確保您貼上的內容包含一個英文逗號（例如：25.03, 121.56）")
    sys.exit()  # 💡 格式錯了就直接優雅地中斷程式，不讓它繼續往下執行

# =================================================================
# 步驟 4：動態組合 API 網址並發送請求（完全移到 try 區塊外面）
# =================================================================
# 利用 f-string 將前面拆解好的 lat, lon 以及讀入的 api_key 動態嵌入網址
# 尾端新增官方特殊參數：
# 1. &units=metric ➔ 將預設的開氏溫標 (Kelvin) 強制轉換為「攝氏度 (°C)」
# 2. &lang=zh_tw   ➔ 將天氣概況敘述（如多雲、晴天）強制轉換為「繁體中文」
# 💡 請特別注意 weather 後方一定要有「?lat=」，英文字母不能漏掉！
url = f"http://api.openweathermap.org/data/2.5/weather?lat={lat}&lon={lon}&appid={api_key}&units=metric&lang=zh_tw"
 

# 使用 requests.get 發送連線請求，並將伺服器回應的所有內容存入 response 變數
response = requests.get(url)  

# =================================================================
# 步驟 5：檢查 HTTP 狀態碼與精準解析資料
# =================================================================
# 判斷 HTTP 狀態碼是否為 200（200 代表網頁連線成功、完全正常）
if response.status_code == 200:
    data = response.json()  # 將伺服器回傳的 JSON 格式純文字，解碼轉換為 Python 的字典 (Dictionary) 結構
    
    print("\n=== 天氣回傳結果 ===")
    print(f"地點: {data.get('name')}")  # data.get('name') 取得城市或地區名稱
    
    # data['weather'][0]['description'] 說明：
    # 因為 OpenWeather API 回傳的 "weather" 欄位是一個「列表 (List)」，形如： "weather": [...]
    # 我們必須先用 [0] 抓出列表中的第一個項目（它是一個字典），接著才能用 ['description'] 拿到中文天氣描述。
    print(f"天氣: {data['weather'][0]['description']}")  
    print(f"溫度: {data['main']['temp']} °C")  # 取得目前溫度（已是攝氏度）

    # =================================================================
    # 風向資料擷取、方位轉換與格式化輸出說明
    # =================================================================

    # 💡 註解 1：從 API 回傳的字典中，安全地安全取出風向角度（0 到 360 度之間的數值）
    # 1. data['wind'] 訪問的是天氣資料中的風速風向區塊。
    # 2. 這裡使用 .get('deg', 0) 而非直接用 data['wind']['deg']，是一種進階的「防呆/防閃退」寫法。
    #    因為如果當天剛好完全沒有風，OpenWeather API 回傳的資料中可能就不會包含 'deg' 這個欄位。
    #    使用 .get('deg', 0) 代表：如果有 'deg' 就取出它的角度；如果沒有，就預設給它 0（度），確保程式絕不當機。
    current_deg = data['wind'].get('deg', 0)

    # 💡 註解 2：呼叫自訂的轉換函式，將角度數字翻譯成中文方位字串
    # 1. 將剛剛取得的角度數字（例如：68）當作參數傳進 get_wind_direction() 函式中。
    # 2. 函式內部會進行條件判斷（例如 68 度落在 67.5 到 112.5 之間），並回傳對應的中文（字串 "東"）。
    # 3. 最後將回傳的結果，指定並儲存到變數 chinese_dir 當中。
    chinese_dir = get_wind_direction(current_deg)

    # 💡 註解 3：利用 f-string（格式化字串）將角度與中文方位完美拼接並列印
    # 1. 在字串前加上小寫 f，代表此字串內允許使用大括號 {} 來直接置入 Python 變數。
    # 2. {current_deg} 會被動態替換為數字 68。
    # 3. {chinese_dir} 會被動態替換為文字 "東"。
    # 4. 大括號外面的 空格、° 符號、以及小括號 ( ) 都會被當作普通文字原封不動地印出來。
    # ➔ 最終在終端機畫面上會呈現最完美的格式：風向: 68 ° (東)
    print(f"風向: {current_deg} ° ({chinese_dir})")


else:
    # 💡 核心亮點：如果伺服器回傳不是 200，這裡會直接攤開所有線索，不再被 try 遮蔽：
    # 常用狀態碼提示：
    # 401 ➔ 代表 API Key 是錯的、或是您剛辦好帳號，金鑰需要等幾小時才會被官方激活。
    # 400 ➔ 代表經緯度網址參數拼錯。
    print(f"\n❌ API 請求失敗！伺服器回傳狀態碼: {response.status_code}")
    print(f"❌ 伺服器回應內容: {response.text}")  # 💡 這行會直接印出 OpenWeather 給您的具體錯誤原因
