import re  # 💡 步驟 1：匯入正規表達式模組

# 💡 步驟 2：定義搜尋規則（Pattern）
# ^      : 限制從字串的最開頭開始比對
# \w+    : 匹配開頭的文字字元（英數底線，至少 1 個字元）
# _      : 精準匹配一個底線
# \d+    : 匹配最後的數字（至少 1 個數字）
# $      : 限制必須在字串的最結尾結束
pattern = r"^\w+_\d+$"

# === 測試輸入範例 1 ===
id1 = "user_123"
# re.search() 會檢查 id1 是否符合規則
if re.search(pattern, id1):
    print("輸出範例 1 : 匹配成功")
else:
    print("輸出範例 1 : 匹配失敗")


# === 測試輸入範例 2 ===
id2 = "_99"
# 因為開頭直接是底線，無法滿足「文字字元 + 底線」的連續結構，因此會失敗
if re.search(pattern, id2):
    print("輸出範例 2 : 匹配成功")
else:
    print("輸出範例 2 : 匹配失敗 (註：開頭需為文字字元)")
