# ====================================================================
# 【步驟 1】引入需要的函式庫
# ====================================================================
import pandas as pd
import numpy as np  # 引入 NumPy，因為題目資料中的 np.nan 需要使用它來代表空值

# ====================================================================
# 【步驟 2】準備原始題目資料
# ====================================================================
# 題目給定的某業務員月營收列表，其中第三個月份為 np.nan (缺失值)
revenue_list = [30000, 45000, np.nan, 38000]

# ====================================================================
# 【步驟 3】將資料建立為 Pandas 的 Series 格式
# ====================================================================
# pd.Series() 是 Pandas 用來處理「一維數值陣列/單一行列資料」的核心物件
# 我們手動將這個 Series 命名為 revenue
revenue = pd.Series(revenue_list)

print("--- 原始的月營收 Series 資料 ---")
print(revenue)
print() # 印出空行，方便閱讀

# ====================================================================
# 【步驟 4】核心操作：計算有紀錄月份的「平均值」
# ====================================================================
# .mean() 是 Pandas 的自動計算平均值函式
# 💡 關鍵觀念：Pandas 的 .mean() 非常聰明，它在計算時會「自動忽略 np.nan」，
# 因此它只會計算 (30000 + 45000 + 38000) / 3 的結果
mean_value = revenue.mean()

print(f"💡 經計算，該業務員有紀錄月份的業績平均值為：{mean_value:.2f} 元\n")

# ====================================================================
# 【步驟 5】核心操作：使用平均值填補缺失月份
# ====================================================================
# 呼叫我們在填空題學過的關鍵指令：.fillna()
# 我們將剛剛算好的平均值 mean_value 丟進去當作填補內容
# 參數 inplace=True 代表直接修改原本的 revenue 資料，不產生新變數
revenue.fillna(mean_value, inplace=True)

# ====================================================================
# 【步驟 6】手動印出最終完成補強後的結果
# ====================================================================
print("--- 經平均值填補空缺後的完整月營收 ---")
print(revenue)
