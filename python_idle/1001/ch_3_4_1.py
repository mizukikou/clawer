# ====================================================================
# 【步驟 1】引入 Pandas 函式庫
# ====================================================================
# 將強大的資料分析套件 pandas 匯入進來，並手動指定別名為 pd（這是業界標準慣例寫法）
import pandas as pd

# ====================================================================
# 【步驟 2】準備原始題目資料
# ====================================================================
# 題目給定的學生簽到表資料，在 Python 中是一個標準的「列表 (List)」格式
# 裡面包含 5 個名字字串，可以注意到「小明」與「小華」重複填寫了
names = ["小明", "小華", "小明", "小美", "小華"]

# ====================================================================
# 【步驟 3】將資料轉換為 Pandas 表格格式 (DataFrame)
# ====================================================================
# 使用 pd.DataFrame() 函式，手動把剛剛的原始列表包裝成 Pandas 的二維表格物件
# 參數 columns=["姓名"] 代表我們手動將這唯一的一縱行（Column）命名為 "姓名"
df = pd.DataFrame(names, columns=["姓名"])

# 先在終端機印出最原始的簽到表，方便對比前後的變化
print("--- 原始簽到表 DataFrame ---")
print(df)
print() # 單純印出一個空行，讓終端機排版好看、好閱讀

# ====================================================================
# 【步驟 4】核心操作：手動刪除重複的資料項目
# ====================================================================
# 呼叫我們在填空題學到的關鍵指令：.drop_duplicates()
# 參數 inplace=True 非常關鍵！它代表「直接在原本的 df 表格上進行覆蓋修改」
# 如果不加這行，原本的 df 就不會發生任何變化
df.drop_duplicates(inplace=True)

# 印出處理完畢、乾淨的表格，此時後面重複出現的名字會被完全剔除
print("--- 刪除重複後的 DataFrame ---")
print(df)
print() 

# ====================================================================
# 【步驟 5】清點並計算最後剩下的人數
# ====================================================================
# len() 是 Python 內建的核心函式（Length 的縮寫），用來計算容器內物件的數量
# 作用在 Pandas DataFrame 上時，它會手動幫你統計這張表格「最後剩下了多少個橫列 (Rows)」
remaining_count = len(df)

# ====================================================================
# 【步驟 6】手動印出最終的任務答案
# ====================================================================
# 使用 f-string (字串格式化) 語法，把計算好的數字動態帶入字串中印出
print(f"【最終答案】最後剩下 {remaining_count} 個人。")
