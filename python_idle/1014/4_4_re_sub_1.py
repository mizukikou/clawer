import re  # 匯入 Python 內建的正則表達式模組

# 模擬從網頁抓下來的雜亂原始碼（包含 HTML 標籤 <div>, <span> 以及純文字）
html_raw = "<div>歡迎來到<span class='highlight'>爬蟲教室</span></div>"

# ==============================================================================
# # 範例 1：使用非貪婪模式移除所有標籤（正確做法）
# 觀念：re.sub(pattern, replacement, string) 的功能是「尋找並替換」。
#       這裡我們把所有符合標籤特徵的文字，全部替換成 ""（空字串），等於是刪除標籤。
# ==============================================================================

# r"<.*?>" 的結構：
# 1. <    -> 匹配固定的角括號開頭
# 2. .    -> 匹配任意字元（除了換行符號）
# 3. *?   -> 【非貪婪量詞】匹配前面的字元 0 次以上，但「只要一遇到後面的邊界就立刻停下」
# 4. >    -> 匹配固定的角括號結尾（遇到它就停）
# 運作：它會把每個標籤分開看待（各別匹配到 <div>、<span...抽取>、</span>、</div>）
clean_text_1 = re.sub(r"<.*?>", "", html_raw)

# 所有標籤都被換成空字串，只留下乾淨的純文字
print(f"範例 1 結果: {clean_text_1}")  
# 輸出結果：歡迎來到爬蟲教室


# ==============================================================================
# # 範例 2：錯誤示範（貪婪模式 Greedy）
# 觀念：如果量詞 `*` 後面沒有加問號 `?`，Regex 會採取「地毯式吞噬」。
#       它會從「最左邊的第一個 <」一路匹配到「最右邊的最後一個 >」，中間所有文字一網打盡。
# ==============================================================================

# r"<.*>" 的結構：
# 1. <    -> 匹配整段文字最左邊的 "<div>" 的 "<"
# 2. .*   -> 【貪婪量詞】瘋狂往後吞，直到碰到整行最後一個出現的 ">" 才會停下來（即 "</div>" 的 ">"）
# 運作：它把整串字串當成一個超大標籤，全部替換成 ""（空字串）
bad_clean = re.sub(r"<.*>", "", html_raw)

# 因為整行文字都被貪婪模式吃掉並替換掉了，所以最後什麼都不剩
print(f"範例 2(錯誤)結果: {bad_clean}")  
# 輸出結果：（空無一物）


# ==============================================================================
# # 範例 3：保留文字，但將標籤替換為換行符號（助於後續分段）
# 觀念：有時候我們不希望文字全部擠在一起，可以將標籤替換成換行符號 `\n`。
# ==============================================================================

# 依然使用非貪婪模式 `r"<.*?>"` 找出各個標籤，但這次把它們通通替換成 "\n"
formatted_text = re.sub(r"<.*?>", "\n", html_raw)

# 標籤原本的位置都會被塞入換行，文字在視覺上會被切開
print(f"範例 3 結果:\n{formatted_text}")  
# 輸出結果：
# (空行，因為原本 <div> 被換成 \n)
# 歡迎來到
# (空行，因為原本 <span...> 被換成 \n)
# 爬蟲教室
# (空行，因為原本 </span> 被換成 \n)
# (空行，因為原本 </div> 被換成 \n)
