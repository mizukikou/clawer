import re  # 匯入 Python 內建的正則表達式模組

# 模擬從網頁爬蟲抓下來、包含換行與縮排的商品說明原始碼
raw_html = """
<li class="item">
    <span class="name"> 高效能
    行動電源 </span>
    <span class="price"> \$ 1,299 </span>
</li>
"""

# ==============================================================================
# # 步驟 1：移除所有標籤
# 觀念：使用非貪婪模式 `.*?` 找出所有的角括號標籤，並將它們替換為空字串（也就是刪除）。
# ==============================================================================

# r"<.*?>" 的結構：
# 1. <  -> 匹配標籤開頭
# 2. .*? -> 【非貪婪模式】匹配任意字元，直到遇到第一個結尾角括號 `>` 就收工
# 3. >  -> 匹配標籤結尾
# 運作：會把 <li>、<span...抽取>、</span>、</li> 這些 HTML 標籤全部抹除
step1 = re.sub(r"<.*?>", "", raw_html)
print(f"步驟 1 結果: '{step1}'")
# 此時 step1 的狀態：標籤不見了，但「高效能」與「行動電源」中間仍有換行，前後也有大量縮排空格
# 內容大致為: "\n     高效能\n    行動電源 \n     \$ 1,299 \n"

# ==============================================================================
# # 步驟 2：將連續空白壓縮成單個空格
# 觀念：利用 `\s+` 抓出所有不規則的連續空格、Tab 或換行，統一格式化成一個標準空格。
# ==============================================================================

# r"\s+" 的結構：
# 1. \s+ -> 匹配 1 個以上的任何空白字元（包含空格、\t、\n 等）
# 運作：將所有雜亂的換行與縮排空格，通通壓縮並替換成一格標準空格 " "
step2 = re.sub(r"\s+", " ", step1)
print(f"步驟 2 結果: '{step2}'")

# 此時 step2 的狀態：文字全部連成一線了，但因為開頭和結尾原本有換行，所以現在最前面和最後面各殘留了一個空格
# 內容變為: " 高效能 行動電源 \$ 1,299 "


# ==============================================================================
# # 步驟 3：去除首尾多餘空格
# 觀念：運用我們上一題聊到的 Python 內建字串方法 `.strip()`，做最後完美的收尾。
# ==============================================================================

# 刪除 step2 字串中最前端與最尾端的單一空格，中間有意義的商品分隔空格則完好保留
final_data = step2.strip()

# ==============================================================================
# # 4. 印出結果對比
# ==============================================================================
print(f"原始資料: {raw_html}")
print(f"清洗完成: {final_data}")
# 最終輸出結果：'高效能 行動電源 \$ 1,299'
