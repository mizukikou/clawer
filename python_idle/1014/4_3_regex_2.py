import re  # 匯入 Python 內建的正則表達式模組

html_data = "價格: 500 元, 價格: 1200 元, 價格: 80 元"

# ==============================================================================
# # 範例 1：沒有分組（傳統做法）
# 觀念：當 Regex 模式中「沒有任何小括號 ()」時，re.findall() 會直接回傳所有「完整匹配」的字串列表。
# ==============================================================================

# r"價格: \d+ 元" 的結構：
# 1. 價格:  -> 匹配固定的文字「價格: 」
# 2. \d+    -> 匹配 1 個以上的數字（如 500, 1200, 80）
# 3.  元    -> 匹配固定的文字「 元」（注意前面有一個空格）
res_no_group = re.findall(r"價格: \d+ 元", html_data)

# 因為沒有小括號分組，所以抓到什麼就吐出什麼
print(f"無分組: {res_no_group}")  
# 輸出結果：['價格: 500 元', '價格: 1200 元', '價格: 80 元']


# ==============================================================================
# # 範例 2：加上分組（只想抓數字部分）
# 觀念：當 Regex 模式中「只有一個小括號 ()」時，re.findall() 的行為會改變！
#       它依然會用整個模式去搜尋，但最後「只會把括號內抓到的東西」收集成列表回傳。
# ==============================================================================

# 我们在 \d+ 加上括號，代表這是我們唯一感興趣的部分
# r"價格: (\d+) 元" 的結構：
# 1. 價格: 與 元  -> 用來在字串中「定位」前後邊界，確保找的是價格，而不是其他數字。
# 2. (\d+)       -> 【唯一的分組】只提取中間這串數字。
res_with_group = re.findall(r"價格: (\d+) 元", html_data)

# 雖然匹配了整段，但因為有括號，最後輸出的列表只保留括號內純數字的部分
print(f"有分組: {res_with_group}")  
# 輸出結果：['500', '1200', '80']


# ==============================================================================
# # 範例 3：多個分組（抓出產品與金額）
# 觀念：當 Regex 模式中「有兩個或更多個小括號 ()」時，re.findall() 會把每一次匹配到的
#       多個群組，打包成一個個「Tuple (元組)」，最後塞進列表裡回傳。
# ==============================================================================

data = "蘋果:100, 香蕉:50, 橘子:30"

# r"(\w+):(\d+)" 的結構：
# 1. (\w+) -> 【第 1 個分組】匹配 1 個以上的英文字母、數字、中文字或底線（這裡代表產品名稱）。
# 2. :     -> 匹配固定的冒號「:」。
# 3. (\d+) -> 【第 2 個分組】匹配 1 個以上的數字（這裡代表產品金額）。
items = re.findall(r"(\w+):(\d+)", data)

# 因為有兩個分組，每一次成功匹配都會產生一個 (Group1, Group2) 的 Tuple
print(f"多分組: {items}")  
# 輸出結果：[('蘋果', '100'), ('香蕉', '50'), ('橘子', '30')]

# --------------------------------------------------
# 方法 A：使用索引值（Index）直接指定印出
# --------------------------------------------------
tuple_1 = items[0]  # 電腦計算從 0 開始，代表第 1 個 tuple
tuple_2 = items[1]  # 代表第 2 個 tuple

print("--- 方法 A：直接印出 Tuple 物件 ---")
print(f"第一個 Tuple 結果: {tuple_1}")
print(f"第二個 Tuple 結果: {tuple_2}")
print()

# --------------------------------------------------
# 方法 B：拆解 Tuple 內容，漂亮格式化輸出
# --------------------------------------------------
print("--- 方法 B：拆解內容（Unpacking）輸出 ---")
# 拆解第 1 個 Tuple
prod1, price1 = items[0]
print(f"第 1 個資料 -> 產品: {prod1}, 金額: {price1}")

# 拆解第 2 個 Tuple
prod2, price2 = items[1]
print(f"第 2 個資料 -> 產品: {prod2}, 金額: {price2}")

# 拆解第 3 個 Tuple
prod3, price3 = items[2]
print(f"第 3 個資料 -> 產品: {prod3}, 金額: {price3}")