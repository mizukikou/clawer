import re  # 匯入 Python 內建的正則表達式模組

# 模擬包含各種雜亂空白、定位符（\t）與換行符（\n）的原始資料
# 注意：最前面和最後面都刻意留有空格
messy_data = " 王小明 \t\t 台北市 \n\n 0912-345-678 "

# ==============================================================================
# # 範例 1：移除開頭與結尾的空白（Regex 版的 strip）
# 觀念：利用錨點符號（^ 與 $）來限定位置，並用「或（|）」將兩套規則組合起來。
# ==============================================================================

# r"^\s+|\s+$" 的結構：
# 1. ^\s+  -> ^ 代表「字串開頭」。\s+ 代表「1個以上的空白字元」。合起來代表「只抓最前面的空白」。
# 2. |     -> 正則表達式的「或（OR）」邏輯。
# 3. \s+$  -> \s+ 代表「1個以上的空白字元」。$ 代表「字串結尾」。合起來代表「只抓最後面的空白」。
# 運作：將最前端與最尾端的空白找出來，並替換成 ""（空字串），中間的 \t 或 \n 則完全不受影響。
res_1 = re.sub(r"^\s+|\s+$", "", messy_data)
# res_strip = messy_data.strip()
print(f"範例 1 結果: '{res_1}'")  
# 輸出結果：'王小明 \t\t 台北市 \n\n 0912-345-678' (注意：文字中間的雜亂空白仍被保留)


# ==============================================================================
# # 範例 2：將「多個」連續空白與換行合併成「單個」空格
# 觀念：這是資料清洗最常用的標準起手式，能把不管是 \t、\n 還是連續空格，通通縮減成一格空白。
# ==============================================================================

# r"\s+" 的結構：
# 1. \s+   -> 匹配任何「連續 1 次以上」的空白字元（包含一般空格、\t、\n 等）。
# 運作：把文字中只要是相連的空白區塊，通通壓縮並替換成一個標準空格 " "。
# 後方搭配 .strip() 是為了順便把「最開頭」和「最結尾」被替換出來的單一空格拔除，確保前後乾淨。
res_2 = re.sub(r"\s+", " ", messy_data).strip()

print(f"範例 2 結果: '{res_2}'")  
# 輸出結果：'王小明 台北市 0912-345-678' (原本雜亂的 \t\t 和 \n\n 通通變成一格空格)


# ==============================================================================
# # 範例 3：徹底移除所有空白（例如處理電話號碼裡的空格）
# 觀念：當資料庫或比對系統需要精準的純字串（如電話、身分證、帳號）時，不容許任何空格干擾。
# ==============================================================================

phone = " 0912 - 345 - 678 "

# r"\s+" 的結構：
# 1. \s+   -> 匹配字串中不論任何位置、任何數量的空白字元。
# 運作：地毯式搜尋所有的空格，通通替換成 ""（空字串），直接讓它們原地消失。
res_3 = re.sub(r"\s+", "", phone)

print(f"範例 3 結果: {res_3}")  
# 輸出結果：0912-345-678 (前後以及數字與橫線間的空格全部不見了)
