import re  # 匯入 Python 內建的正則表達式模組

# 1. 定義要解析的文字字串（依輸入範例）
text_data = "本週特價：泡麵=35 元, 麵包=20 元, 牛奶=60 元"

# 2. 撰寫 Regex 模式：使用兩個括號分別包裹產品名稱與數字
# r"([^\s=]+)=(\d+)\s*元" 的詳細結構：
#   - ([^\s=]+) : 【第 1 個括號】匹配 1 個以上「不是空格、不是等號」的文字（擷取產品名稱，例如泡麵）
#   - =         : 匹配固定的等號「=」（作為定位邊界，不被擷取）
#   - (\d+)     : 【第 2 個括號】匹配 1 個以上的數字（擷取金額數字，例如 35）
#   - \s*元     : 匹配可能存在的空格與固定的「元」字（作為定位邊界，不被擷取）
pattern = r"([^\s=]+)=(\d+)\s*元"

# 3. 使用 re.findall() 進行地毯式搜索
# 因為模式內有兩個小括號，findall 會自動將結果打包成 List of Tuples
results = re.findall(pattern, text_data)

# 4. 印出最終結果
print(results)
