import re  # 匯入 Python 內建的正則表達式（Regex）模組

# 目標：從身份證字號中提取「性別碼」
id_text = "我的身份證字號是 A123456789"

# --- Regex 模式解析 ---
# r"([A-Z])([12])\d{8}" 的詳細結構如下：
# 1. r"..."      : 原始字串（Raw String），避免轉義字元 \ 產生衝突。
# 2. ([A-Z])    : 【第 1 個分組】匹配一個大寫英文字母（代表縣市碼）。
# 3. ([12])     : 【第 2 個分組】匹配字元 '1' 或 '2'（1 代表男性，2 代表女性）。
# 4. \d{8}      : 匹配連續 8 個數字（身份證字號後方的流水號與檢查碼）。
match = re.search(r"([A-Z])([12])\d{8}", id_text)

# re.search() 會在字串中搜尋，若找到符合的格式，會回傳一個「Match 物件」；找不到則回傳 None。
if match:
    # --- match.group() 分組提取解析 ---
    
    # group(0) 或 group() 代表「整個 Regex 模式所匹配到的完整字串」
    print(f"完整匹配: {match.group(0)}")  # 輸出: A123456789
    
    # group(1) 代表第一個左括號 `([A-Z])` 所包起來的內容
    print(f"縣市代碼: {match.group(1)}")  # 輸出: A
    
    # group(2) 代表第二個左括號 `([12])` 所包起來的內容
    print(f"性別代碼: {match.group(2)}")  # 輸出: 1
    
else:
    # 如果字串中完全找不到符合「1位大寫字母 + 1或2 + 8位數字」的組合，就會執行這裡
    print("格式不符")
